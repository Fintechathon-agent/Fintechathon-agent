"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const os = require("node:os");
const { chromium } = require("playwright");
const { CASES } = require("../model.js");
const { pathToFileURL } = require("node:url");
const out = process.env.RISK_DEMO_ARTIFACTS || path.join(os.tmpdir(), "finance-risk-demo-v01");
fs.mkdirSync(out, { recursive: true });
(async () => {
  const launch = { headless: true };
  if (process.env.RISK_DEMO_BROWSER) launch.executablePath = process.env.RISK_DEMO_BROWSER;
  const browser = await chromium.launch(launch);
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce" });
    const errors = [], remoteRequests = [];
    page.on("pageerror", error => errors.push(error.message));
    page.on("request", request => { if (/^https?:/.test(request.url())) remoteRequests.push(request.url()); });
    await page.goto(process.env.RISK_DEMO_URL || pathToFileURL(path.join(__dirname, "../index.html")).href);
    const choose = async id => { await page.locator("#case-filter").selectOption("all"); await page.locator(`[data-case="${id}"]`).click(); };
    const check = async () => { await page.locator("#run-check").click(); await page.waitForFunction(() => document.getElementById("verdict").textContent.includes("检查中") === false); };
    const approve = async () => { for (const input of await page.locator("[data-accept]").all()) await input.check(); await page.locator("#confirm-plan").check(); await page.locator("#approve").click(); };
    const execute = async () => { await page.locator("#execute").click(); await page.waitForFunction(() => !document.getElementById("execution-title").textContent.includes("执行中")); };
    for (const c of CASES) {
      await choose(c.id);
      assert.equal(await page.locator("#execute").isDisabled(), true, `${c.id}: pending`);
      if (c.focusOptions) await page.locator("#focus-select").selectOption({ label: c.focusOptions[0] });
      await check();
      const expectedLabel = { ALLOW: "通过", REVIEW: "需要复核", BLOCK: "阻止" }[c.expected];
      assert.ok((await page.locator("#verdict strong").innerText()).includes(expectedLabel), c.id);
      assert.equal(await page.locator(".rule").count(), 10);
      assert.equal(await page.locator("#execute").isDisabled(), true);
      if (c.expected === "BLOCK" || c.repairable) { assert.equal(await page.locator("#confirm-plan").isDisabled(), true); }
      else { await approve(); assert.equal(await page.locator("#execute").isEnabled(), true, c.id); }
    }
    await choose("multiple-review"); await check();
    await page.locator("#confirm-plan").check();
    await page.locator("[data-accept]").first().check();
    assert.equal(await page.evaluate(() => document.activeElement?.getAttribute("data-accept")), await page.locator("[data-accept]").first().getAttribute("data-accept"));
    assert.equal(await page.locator("#approve").isDisabled(), true);
    for (const input of await page.locator("[data-accept]").all()) await input.check();
    assert.equal(await page.locator("#approve").isEnabled(), true);
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({ path: path.join(out, "desktop.png"), fullPage: true });
    await page.locator(".approval-section").screenshot({ path: path.join(out, "desktop-approval.png") });
    await page.locator("#architecture img").screenshot({ path: path.join(out, "architecture.png") });
    await choose("version-change"); await check(); await approve();
    await page.locator("#invalidate").click(); assert.equal(await page.locator("#execute").isDisabled(), true);
    assert.ok((await page.locator("#rules").innerText()).includes("APPROVAL_INVALIDATED"));
    assert.ok((await page.locator("#state-strip").innerText()).includes("已失效"));
    await check(); await approve(); assert.equal(await page.locator("#execute").isEnabled(), true);
    await choose("reject"); await check(); await page.locator("#reject").click(); assert.equal(await page.locator("#execute").isDisabled(), true);
    await page.locator("#reset-case").click(); await check(); await approve(); await page.locator("#revoke").click(); assert.equal(await page.locator("#execute").isDisabled(), true);
    await choose("data-invalid"); await check(); await page.locator("#repair-data").click();
    await page.waitForFunction(() => document.getElementById("verdict").classList.contains("allow"));
    assert.equal(await page.locator("#execute").isDisabled(), true);
    await choose("repeat"); await check(); await approve(); await execute(); await page.locator("#repeat").click();
    let exported = JSON.parse(await page.locator("#audit-json").textContent());
    assert.equal(exported.write_count, 1);
    assert.equal(exported.records.filter(a => a.event_type === "EXECUTION_STARTED").length, 1);
    await choose("unknown-result"); await check(); await approve(); await execute();
    assert.equal(await page.locator("#execute").isDisabled(), true);
    assert.equal(JSON.parse(await page.locator("#audit-json").textContent()).write_count, null);
    await page.locator("#reconcile").click();
    exported = JSON.parse(await page.locator("#audit-json").textContent()); assert.equal(exported.write_count, 1);
    assert.equal(exported.records.filter(a => a.event_type === "EXECUTION_STARTED").length, 1);
    await choose("idempotency-conflict"); await check(); await approve(); await execute(); await page.locator("#invalidate-key").click();
    assert.equal(await page.locator("#repeat").isDisabled(), true); assert.equal(await page.locator("#verdict strong").innerText(), "阻止");
    await choose("audit-failed"); await check(); assert.equal(await page.locator("#execute").isDisabled(), true);
    assert.equal(JSON.parse(await page.locator("#audit-json").textContent()).records.length, 0);
    await choose("improvement-blocked"); await page.locator("#focus-select").selectOption({ index: 1 }); await check();
    assert.equal(await page.locator("#confirm-plan").isDisabled(), true);
    await page.setViewportSize({ width: 390, height: 844 });
    await choose("multiple-review"); await check();
    await page.evaluate(() => window.scrollTo(0, 0));
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    await page.screenshot({ path: path.join(out, "mobile.png"), fullPage: true });
    await page.locator(".approval-section").screenshot({ path: path.join(out, "mobile-approval.png") });
    assert.equal(await page.evaluate(() => document.querySelector("#architecture img").naturalWidth > 0), true);
    assert.deepEqual(errors, []);
    if (process.env.RISK_DEMO_URL) assert.ok(remoteRequests.every(url => new URL(url).origin === new URL(process.env.RISK_DEMO_URL).origin));
    else assert.deepEqual(remoteRequests, []);
    const safeRequests = remoteRequests.filter(url => !new URL(url).pathname.startsWith("/cdn-cgi/")).map(url => new URL(url).origin + new URL(url).pathname);
    const report = { prototype_only: true, fixture_count: CASES.length, rules: 10, viewport_widths: [1440, 390], javascript_errors: errors, remote_requests: safeRequests, flows: ["all fixed cases", "partial acceptance", "version invalidation", "reject and revoke", "repair", "idempotent replay", "unknown reconciliation", "content conflict", "audit failure", "improvement denial"], artifacts: out };
    fs.writeFileSync(path.join(out, "browser-report.json"), JSON.stringify(report, null, 2));
    process.stdout.write(JSON.stringify(report, null, 2) + "\n");
  } finally { await browser.close(); }
})().catch(error => { process.stderr.write(error.stack + "\n"); process.exitCode = 1; });
